"""Fail on diagrams that PlantUML rendered as an error image.

When Graphviz is missing, `./gradlew asciidoctor` still succeeds: PlantUML
draws "Cannot find Graphviz" in place of each diagram, and the docs embed that
image as base64. That is how docs/1.16.0 and docs/1.17.0-SNAPSHOT were first
published. This decodes every embedded diagram: SVGs are searched for
PlantUML's error text, and PlantUML PNGs, whose metadata is the same whether or
not they rendered, for the green PlantUML draws that text in.
"""

import argparse
import base64
import binascii
import re
import struct
import sys
import zlib
from pathlib import Path
from typing import List, Optional

EMBEDDED_IMAGE = re.compile(
    r"""src=["']data:image/(svg\+xml|png);base64,([A-Za-z0-9+/=]+)["']"""
)

# Text PlantUML draws into its error images.
ERROR_MARKERS = (
    "Cannot find Graphviz",
    "Dot Executable:",
    "Syntax Error?",
)

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
PLANTUML_PNG_TAG = b"Generated by http://plantuml.com"
# The colour of PlantUML's error text (#33FF02). No working diagram in
# docs/1.12.1 to docs/1.15.0 uses it.
ERROR_GREEN = b"\x33\xff\x02"
PNG_ERROR_MARKER = "PlantUML error image (PNG)"


def png_chunks(png: bytes):
    """Yield (type, data) for each chunk of a PNG."""
    pos = len(PNG_SIGNATURE)
    while pos + 8 <= len(png):
        length, kind = struct.unpack(">I4s", png[pos : pos + 8])
        yield kind, png[pos + 8 : pos + 8 + length]
        pos += 12 + length


def paeth(left: int, up: int, up_left: int) -> int:
    p = left + up - up_left
    pa, pb, pc = abs(p - left), abs(p - up), abs(p - up_left)
    if pa <= pb and pa <= pc:
        return left
    if pb <= pc:
        return up
    return up_left


def unfilter_row(kind: int, row: bytearray, previous: bytearray, bpp: int) -> None:
    """Undo a PNG row filter in place (https://www.w3.org/TR/png/#9Filters)."""
    for x in range(len(row)):
        left = row[x - bpp] if x >= bpp else 0
        up = previous[x]
        if kind == 1:
            predictor = left
        elif kind == 2:
            predictor = up
        elif kind == 3:
            predictor = (left + up) // 2
        elif kind == 4:
            predictor = paeth(left, up, previous[x - bpp] if x >= bpp else 0)
        else:
            return
        row[x] = (row[x] + predictor) & 0xFF


def png_rows(png: bytes) -> Optional[List[bytes]]:
    """RGB pixel rows of an 8-bit, non-interlaced RGB or RGBA PNG, else None."""
    if not png.startswith(PNG_SIGNATURE):
        return None
    chunks = list(png_chunks(png))
    header = next((data for kind, data in chunks if kind == b"IHDR"), None)
    if header is None:
        return None
    width, height, bit_depth, colour_type, _, _, interlace = struct.unpack(">IIBBBBB", header)
    if bit_depth != 8 or colour_type not in (2, 6) or interlace != 0:
        return None
    bpp = 3 if colour_type == 2 else 4
    stride = width * bpp
    raw = zlib.decompress(b"".join(data for kind, data in chunks if kind == b"IDAT"))
    rows, previous = [], bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        row = bytearray(raw[start + 1 : start + 1 + stride])
        unfilter_row(raw[start], row, previous, bpp)
        # Drop the alpha channel so every row is plain RGB triples.
        rows.append(bytes(row) if bpp == 3 else bytes(b for i, b in enumerate(row) if i % 4 != 3))
        previous = row
    return rows


def is_plantuml_error_png(png: bytes) -> bool:
    # Only PlantUML's own PNGs are decoded; the large screenshots are skipped.
    if PLANTUML_PNG_TAG not in png:
        return False
    rows = png_rows(png)
    if rows is None:
        return False
    return any(
        row[i : i + 3] == ERROR_GREEN for row in rows for i in range(0, len(row), 3)
    )


def broken_diagrams(html: str) -> List[str]:
    """Return the error marker found in each broken embedded diagram, in page order."""
    found = []
    for match in EMBEDDED_IMAGE.finditer(html):
        try:
            image = base64.b64decode(match.group(2))
        except binascii.Error:
            continue
        if match.group(1) == "png":
            if is_plantuml_error_png(image):
                found.append(PNG_ERROR_MARKER)
            continue
        svg = image.decode("utf-8", errors="ignore")
        for marker in ERROR_MARKERS:
            if marker in svg:
                found.append(marker)
                break
    return found


# Broken diagrams already published before this check existed, per version.
# A version is only allowed exactly this many; any other count fails.
KNOWN_BROKEN = {
    # The batch-jobs "Fault-tolerance scenarios" diagram (a PNG), broken since
    # the 1.13.0 release. 1.13.0 is EOL, so it is not being rebuilt.
    "1.13.0": 1,
}


def check_docs(docs_root: Path, known_broken=None) -> List[str]:
    known_broken = KNOWN_BROKEN if known_broken is None else known_broken
    errors = []
    for page in sorted(docs_root.glob("*/index.html")):
        markers = broken_diagrams(page.read_text(encoding="utf-8", errors="ignore"))
        if len(markers) == known_broken.get(page.parent.name, 0):
            continue
        for marker in markers:
            errors.append(f"{page}: diagram rendered as a PlantUML error ('{marker}')")
        if not markers:
            errors.append(f"{page}: no broken diagrams left; remove it from KNOWN_BROKEN")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--docs-root",
        default="docs",
        help="Directory holding VERSION/index.html pages (default: docs).",
    )
    args = parser.parse_args()

    errors = check_docs(Path(args.docs_root))
    if errors:
        print("Broken diagrams found. Install Graphviz (`dot`) and rebuild the docs:")
        for error in errors:
            print(f"  - {error}")
        return 1
    print("Docs diagram check passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
